#!/usr/bin/env node
// Generates src/styles/i18n-fil-type.css: tighter letter-spacing for the Filipino pages (html[lang="fil"]).
//
// Filipino labels run 30-60% longer than English ("TINGNAN ANG MEMBERSHIP" vs "EXPLORE MEMBERSHIP"). The site's
// uppercase labels, buttons, eyebrows, chips, tabs and footer headings are widely tracked (.08em-.28em), which makes the
// longer words wrap early and read loosely. This script copies every rule whose letter-spacing is at least MIN_EM,
// prefixes each selector with html[lang="fil"], and scales the value by SCALE. English is untouched.
//
// Each override keeps its original selector, media query and source order, and every selector gains the same
// specificity (+0,1,1), so the relative cascade between the original rules is preserved.
//
//   node scripts/gen-fil-type.mjs           regenerate the file (run after changing letter-spacing in a source file)
//   node scripts/gen-fil-type.mjs --check   exit 1 if the generated file is out of date
//
// Uses postcss, which ships with Next (no extra install).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const SCALE = 0.6;
const MIN_EM = 0.04;
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "src", "styles", "i18n-fil-type.css");

// Stylesheets used on the public (localized) pages, in cascade order: globals.css and its @imports first, then the
// stylesheets imported by individual components. Admin, login, account and checkout stay English and are left out.
const SOURCES = [
  "src/app/globals.css",
  "src/styles/legal.css",
  "src/styles/find-us.css",
  "src/styles/join-flow.css",
  "src/styles/consent.css",
  "src/styles/social.css",
  "src/styles/ai-label.css",
  "src/components/payments/payments.css",
  "src/components/home/HomeOfferModal.css",
  "src/app/membership/membership.css",
  "src/app/membership/founding/founding.css",
];
const GLOBAL_IMPORTS = /@import\s+"\.\.\/styles\/([\w-]+\.css)";/g;

const FIL = 'html[lang="fil"]';
function prefix(selector) {
  const s = selector.trim();
  if (s.startsWith(FIL)) return s;
  if (/^html(?![\w-])/.test(s)) return FIL + s.slice(4);
  if (/^:root(?![\w-])/.test(s)) return FIL + s.slice(5);
  return `${FIL} ${s}`;
}

/** Wide em values are scaled; anything else (0, normal, px, negative, var()) is null. */
function scaled(value) {
  const m = /^(\.\d+|\d+(?:\.\d+)?)em$/.exec(value.trim());
  if (!m || parseFloat(m[1]) < MIN_EM) return null;
  const v = Math.round(parseFloat(m[1]) * SCALE * 1000) / 1000;
  return `${String(v).replace(/^0\./, ".")}em`;
}

function insideKeyframes(node) {
  for (let p = node.parent; p; p = p.parent) if (p.type === "atrule" && /keyframes$/.test(p.name)) return true;
  return false;
}

/** The chain of at-rules (@media/@supports/@container) around a rule, outermost first. */
function wrappers(node) {
  const out = [];
  for (let p = node.parent; p && p.type !== "root"; p = p.parent) if (p.type === "atrule") out.unshift(`@${p.name} ${p.params}`);
  return out;
}

function collect(file, blocks) {
  const css = readFileSync(join(root, file), "utf8");
  const tree = postcss.parse(css, { from: file });
  const lines = [];
  tree.walkRules((rule) => {
    if (insideKeyframes(rule)) return;
    let decl = null;
    rule.each((d) => { if (d.type === "decl" && d.prop === "letter-spacing") decl = d; });
    if (!decl) return;
    // Rules that are not scaled (letter-spacing: 0, normal, px, negative) are still copied unchanged: they often reset a
    // wider value from a broader rule, and they must keep beating its (now more specific) Filipino override.
    const value = (scaled(decl.value) ?? decl.value) + (decl.important ? " !important" : "");
    const sel = rule.selectors.map(prefix).join(", ");
    const wrap = wrappers(rule);
    const line = `${sel} { letter-spacing: ${value}; }`;
    lines.push(wrap.length ? `${wrap.map((w) => `${w} { `).join("")}${line}${" }".repeat(wrap.length)}` : line);
  });
  if (lines.length) blocks.push(`/* ${file} */`, ...lines);
  return lines.length;
}

const files = [];
for (const src of SOURCES) {
  if (!existsSync(join(root, src))) continue;
  if (src.endsWith("globals.css")) {
    for (const [, name] of readFileSync(join(root, src), "utf8").matchAll(GLOBAL_IMPORTS)) {
      if (name !== "i18n-fil-type.css") files.push(`src/styles/${name}`); // never read our own output
    }
  }
  files.push(src);
}

const blocks = [];
let count = 0;
for (const f of files) count += collect(f, blocks);
const output = `/* GENERATED by scripts/gen-fil-type.mjs: do not edit by hand. Run \`npm run i18n:fil-type\` after changing a
   letter-spacing in the stylesheets listed there. Filipino pages only: letter-spacing of ${MIN_EM}em and wider is scaled
   by ${SCALE} so the longer Filipino labels, buttons, eyebrows and chips fit and read as words. English is unchanged. */
${blocks.join("\n")}
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== output) {
    console.error(`${relative(root, OUT)} is out of date. Run: npm run i18n:fil-type`);
    process.exit(1);
  }
  console.log(`${relative(root, OUT)} is up to date.`);
} else {
  writeFileSync(OUT, output);
  console.log(`Wrote ${relative(root, OUT)} (${count} overrides from ${files.length} files).`);
}
